let currentLang = localStorage.getItem("gb_lang") || "tr";

function t(key) {
  const lang = translations[currentLang] || translations.tr;
  return lang[key] || translations.tr[key] || key;
}

function setLanguage(code) {
  currentLang = code;
  localStorage.setItem("gb_lang", code);
  document.documentElement.lang = code;
  document.documentElement.dir = (code === "ar" || code === "fa") ? "rtl" : "ltr";
  applyTranslations();
  buildLangMenu();
  const l = LANGS.find(x => x.code === code) || LANGS[0];
  const flagEl = document.getElementById("langFlag");
  const nameEl = document.getElementById("langName");
  if (flagEl) flagEl.innerHTML = `<img src="https://flagcdn.com/w40/${l.flag}.png" alt="${l.flag}" style="width:20px;height:14px;object-fit:cover;border-radius:2px;vertical-align:middle;display:inline-block">`;
  if (nameEl) nameEl.textContent = l.name;
  if (typeof window.refreshDynamicContent === "function") {
    window.refreshDynamicContent();
  }
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = t(key);
    if (el.hasAttribute("data-i18n-html")) el.innerHTML = val;
    else el.textContent = val;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.placeholder = t(el.getAttribute("data-i18n-ph"));
  });
  document.querySelectorAll("[data-i18n-opt]").forEach(el => {
    el.textContent = t(el.getAttribute("data-i18n-opt"));
  });
}

function buildLangMenu() {
  const menu = document.getElementById("langMenu");
  if (!menu) return;
  menu.innerHTML = LANGS.map(l => `
    <button class="lang-option ${l.code === currentLang ? "active" : ""}" data-lang="${l.code}">
      <span class="flag"><img src="https://flagcdn.com/w40/${l.flag}.png" alt="${l.flag}" style="width:20px;height:14px;object-fit:cover;border-radius:2px;vertical-align:middle;display:inline-block"></span>
      <span>${l.name}</span>
    </button>
  `).join("");
}