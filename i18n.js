let currentLang = "tr";
try { currentLang = localStorage.getItem("gb_lang") || "tr"; } catch(e) {}
if (!I18N[currentLang]) currentLang = "tr";

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.tr[key] || key;
}

function flagImg(code, size) {
  var w = size === "small" ? 20 : 22;
  var h = size === "small" ? 14 : 16;
  return '<img src="https://flagcdn.com/w40/' + code + '.png" alt="' + code + '" style="width:' + w + 'px;height:' + h + 'px;object-fit:cover;border-radius:2px;vertical-align:middle;display:inline-block">';
}

function buildLangMenu() {
  const menu = document.getElementById("langMenu");
  if (!menu) return;
  menu.innerHTML = LANGS.map(function(l) {
    var active = (l.code === currentLang) ? "active" : "";
    return '<button type="button" class="lang-option ' + active + '" data-lang="' + l.code + '">' +
           '<span class="flag">' + flagImg(l.flag) + '</span>' +
           '<span>' + l.name + '</span></button>';
  }).join("");
}

function setLanguage(code) {
  if (!I18N[code]) return;
  currentLang = code;
  try { localStorage.setItem("gb_lang", code); } catch(e) {}
  var l = LANGS.find(function(x) { return x.code === code; });
  var flagEl = document.getElementById("langFlag");
  var nameEl = document.getElementById("langName");
  if (flagEl) flagEl.innerHTML = flagImg(l.flag, "small");
  if (nameEl) nameEl.textContent = l.name;
  document.documentElement.dir = (code === "ar" || code === "fa" || code === "ku") ? "rtl" : "ltr";
  document.documentElement.lang = code;
  buildLangMenu();
  if (typeof applyTranslations === "function") applyTranslations();
  if (typeof updateProfileSection === "function") updateProfileSection();
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(function(el) {
    var txt = t(el.dataset.i18n);
    if (el.dataset.i18nHtml === "1") el.innerHTML = txt;
    else el.textContent = txt;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(function(el) {
    el.placeholder = t(el.dataset.i18nPh);
  });
  document.querySelectorAll("[data-i18n-opt]").forEach(function(el) {
    el.textContent = t(el.dataset.i18nOpt);
  });
  var pc = document.getElementById("profileCount");
  if (pc) {
    if (typeof currentUser !== "undefined" && (!currentUser || !myProfile)) pc.textContent = t("lockedTitle");
    else if (typeof allProfiles !== "undefined" && allProfiles.length) pc.textContent = allProfiles.length + " " + t("membersFound");
    else pc.textContent = t("loading");
  }
}