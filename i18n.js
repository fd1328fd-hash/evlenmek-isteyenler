let currentLang = (() => {
  try { return localStorage.getItem("gb_lang") || "tr"; } catch(e) { return "tr"; }
})();

function t(key) {
  return (translations[currentLang] && translations[currentLang][key])
    || (translations.tr && translations.tr[key])
    || key;
}

function setLanguage(code) {
  if (!translations[code]) return;
  currentLang = code;
  try { localStorage.setItem("gb_lang", code); } catch(e) {}
  document.documentElement.dir = (code === "ar" || code === "fa") ? "rtl" : "ltr";
  document.documentElement.lang = code;
  const l = LANGS.find(x => x.code === code);
  const flagEl = document.getElementById("langFlag");
  const nameEl = document.getElementById("langName");
  if (flagEl && l) flagEl.innerHTML = '<img src="https://flagcdn.com/w40/' + l.flag + '.png" alt="' + l.flag + '" style="width:20px;height:14px;object-fit:cover;border-radius:2px;vertical-align:middle;display:inline-block">';
  if (nameEl && l) nameEl.textContent = l.name;
  applyTranslations();
  buildLangMenu();
  if (typeof loadProfiles === "function") loadProfiles();
  if (typeof renderNotifications === "function") renderNotifications();
  if (typeof refreshConversationList === "function") refreshConversationList();
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = t(key);
    if (el.hasAttribute("data-i18n-html")) el.innerHTML = val;
    else el.textContent = val;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
  document.querySelectorAll("[data-i18n-opt]").forEach(el => {
    el.textContent = t(el.getAttribute("data-i18n-opt"));
  });
}

function buildLangMenu() {
  const menu = document.getElementById("langMenu");
  if (!menu) return;
  menu.innerHTML = LANGS.map(l => `
    <button class="lang-option ${l.code === currentLang ? "active" : ""}" data-lang="${l.code}" type="button">
      <span class="flag"><img src="https://flagcdn.com/w40/${l.flag}.png" alt="${l.flag}" style="width:20px;height:14px;object-fit:cover;border-radius:2px"></span>
      <span>${l.name}</span>
    </button>
  `).join("");
}